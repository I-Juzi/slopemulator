use std::{collections::HashSet, fmt};

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum StartLine {
    Request { protocol: String, command: String },
    Response { status: u32, reason: String },
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Header {
    pub name: String,
    pub value: String,
}

/// `l` is generated by the encoder. Do not put it in `headers`.
/// Names are normalized to lowercase by the decoder; values stay unchanged.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Frame {
    pub start: StartLine,
    pub headers: Vec<Header>,
    pub body: Vec<u8>,
}

/// `None` means a request. `Some(false)` means a partial reply.
/// `Some(true)` means a complete reply. IDs are nonzero.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Transaction {
    pub id: u32,
    pub complete: Option<bool>,
    pub sequence: u32,
}

impl Transaction {
    pub fn parse(value: &str) -> Result<Self, Error> {
        let split = value.find(['r', 'R']);
        let (id, complete, sequence) = if let Some(pos) = split {
            let sequence = &value[pos + 1..];
            (
                decimal(&value[..pos])?,
                Some(value.as_bytes()[pos] == b'R'),
                if sequence.is_empty() {
                    0
                } else {
                    decimal(sequence)?
                },
            )
        } else {
            (decimal(value)?, None, 0)
        };
        let result = Self {
            id,
            complete,
            sequence,
        };
        result.validate()?;
        Ok(result)
    }

    fn validate(self) -> Result<(), Error> {
        if self.id == 0 || (self.complete.is_none() && self.sequence != 0) {
            return Err(Error::InvalidTransaction);
        }
        Ok(())
    }

    pub fn to_header(self) -> Result<Header, Error> {
        self.validate()?;
        let mut value = self.id.to_string();
        if let Some(complete) = self.complete {
            value.push(if complete { 'R' } else { 'r' });
            if self.sequence != 0 {
                value.push_str(&self.sequence.to_string());
            }
        }
        Ok(Header {
            name: "s".into(),
            value,
        })
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Error {
    HeaderTooLarge,
    BodyTooLarge,
    InvalidStartLine,
    InvalidHeader,
    DuplicateHeader,
    MissingLength,
    InvalidLength,
    InvalidTransaction,
    UnsupportedEncoding,
}

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        // Never include input text: headers can contain bearer secrets.
        write!(f, "STS frame error: {self:?}")
    }
}
impl std::error::Error for Error {}

/// Local limits, not recovered platform defaults.
#[derive(Clone, Copy, Debug)]
pub struct Codec {
    pub max_header_bytes: usize,
    pub max_body_bytes: usize,
}
impl Default for Codec {
    fn default() -> Self {
        Self {
            max_header_bytes: 32_767,
            max_body_bytes: 1_048_576,
        }
    }
}

impl Codec {
    /// Decode one frame without changing input. `None` means incomplete input.
    /// The byte count excludes any next frame. Errors require closing/resetting
    /// the caller's stream; this codec does not attempt resynchronization.
    pub fn decode(&self, input: &[u8]) -> Result<Option<(Frame, usize)>, Error> {
        let search = &input[..input.len().min(self.max_header_bytes)];
        let Some(end) = search.windows(4).position(|w| w == b"\r\n\r\n") else {
            if input.len() > self.max_header_bytes {
                return Err(Error::HeaderTooLarge);
            }
            return Ok(None);
        };
        let head_bytes = end.checked_add(4).ok_or(Error::HeaderTooLarge)?;
        if head_bytes > self.max_header_bytes {
            return Err(Error::HeaderTooLarge);
        }
        let head = std::str::from_utf8(&input[..end]).map_err(|_| Error::InvalidHeader)?;
        let mut lines = head.split("\r\n");
        let start = parse_start(lines.next().ok_or(Error::InvalidStartLine)?)?;
        let mut headers = Vec::new();
        let mut seen = HashSet::new();
        let mut length = None;
        for line in lines {
            let (name, value) = line.split_once(':').ok_or(Error::InvalidHeader)?;
            validate_header(name, value)?;
            let name = name.to_ascii_lowercase();
            // RouteSrv supports several targets (13-routesrv.md §5).
            // All other headers, including framing and transaction ids, are unique.
            if !seen.insert(name.clone()) && name != "t" {
                return Err(Error::DuplicateHeader);
            }
            if name == "l" {
                length = Some(decimal(value).map_err(|_| Error::InvalidLength)? as usize);
            } else {
                headers.push(Header {
                    name,
                    value: value.into(),
                });
            }
        }
        let length = length.ok_or(Error::MissingLength)?;
        if length > self.max_body_bytes {
            return Err(Error::BodyTooLarge);
        }
        let total = head_bytes.checked_add(length).ok_or(Error::BodyTooLarge)?;
        if input.len() < total {
            return Ok(None);
        }
        Ok(Some((
            Frame {
                start,
                headers,
                body: input[head_bytes..total].to_vec(),
            },
            total,
        )))
    }

    pub fn encode(&self, frame: &Frame) -> Result<Vec<u8>, Error> {
        if frame.body.len() > self.max_body_bytes || frame.body.len() > u32::MAX as usize {
            return Err(Error::BodyTooLarge);
        }
        let mut output = Vec::new();
        match &frame.start {
            StartLine::Request { protocol, command } => {
                if !segment(protocol) || !segment(command) {
                    return Err(Error::InvalidStartLine);
                }
                self.append(&mut output, b"POST /")?;
                self.append(&mut output, protocol.as_bytes())?;
                self.append(&mut output, b"/")?;
                self.append(&mut output, command.as_bytes())?;
                self.append(&mut output, b" STS/1.0\r\n")?;
            }
            StartLine::Response { status, reason } => {
                if !printable(reason) {
                    return Err(Error::InvalidStartLine);
                }
                self.append(&mut output, format!("STS/1.0 {status} ").as_bytes())?;
                self.append(&mut output, reason.as_bytes())?;
                self.append(&mut output, b"\r\n")?;
            }
        }
        let mut seen = HashSet::new();
        for header in &frame.headers {
            validate_header(&header.name, &header.value)?;
            let name = header.name.to_ascii_lowercase();
            if name == "l" || (!seen.insert(name.clone()) && name != "t") {
                return Err(Error::DuplicateHeader);
            }
            self.append(&mut output, name.as_bytes())?;
            self.append(&mut output, b":")?;
            self.append(&mut output, header.value.as_bytes())?;
            self.append(&mut output, b"\r\n")?;
        }
        self.append(
            &mut output,
            format!("l:{}\r\n\r\n", frame.body.len()).as_bytes(),
        )?;
        output.extend_from_slice(&frame.body);
        Ok(output)
    }

    fn append(&self, output: &mut Vec<u8>, bytes: &[u8]) -> Result<(), Error> {
        if output
            .len()
            .checked_add(bytes.len())
            .ok_or(Error::HeaderTooLarge)?
            > self.max_header_bytes
        {
            return Err(Error::HeaderTooLarge);
        }
        output.extend_from_slice(bytes);
        Ok(())
    }
}

fn parse_start(line: &str) -> Result<StartLine, Error> {
    if let Some(rest) = line.strip_prefix("POST /") {
        let path = rest
            .strip_suffix(" STS/1.0")
            .ok_or(Error::InvalidStartLine)?;
        let (protocol, command) = path.split_once('/').ok_or(Error::InvalidStartLine)?;
        if segment(protocol) && segment(command) {
            return Ok(StartLine::Request {
                protocol: protocol.into(),
                command: command.into(),
            });
        }
    } else if let Some(rest) = line.strip_prefix("STS/1.0 ") {
        let (status, reason) = rest.split_once(' ').ok_or(Error::InvalidStartLine)?;
        if printable(reason) {
            return Ok(StartLine::Response {
                status: decimal(status).map_err(|_| Error::InvalidStartLine)?,
                reason: reason.into(),
            });
        }
    }
    Err(Error::InvalidStartLine)
}

fn segment(s: &str) -> bool {
    !s.is_empty()
        && s.bytes()
            .all(|b| b.is_ascii_alphanumeric() || b"-_.".contains(&b))
}
fn printable(s: &str) -> bool {
    s.bytes().all(|b| (b' '..=b'~').contains(&b))
}
fn validate_header(name: &str, value: &str) -> Result<(), Error> {
    if name.is_empty()
        || !name.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-')
        || !printable(value)
    {
        return Err(Error::InvalidHeader);
    }
    if name.eq_ignore_ascii_case("x") || name.eq_ignore_ascii_case("transfer-encoding") {
        return Err(Error::UnsupportedEncoding);
    }
    // Only the short length header is in this subset. Reject aliases, rather
    // than accepting ambiguous framing when a peer uses different rules.
    if name.eq_ignore_ascii_case("content-length") {
        return Err(Error::InvalidLength);
    }
    if name.eq_ignore_ascii_case("s") {
        Transaction::parse(value).map_err(|_| Error::InvalidTransaction)?;
    }
    Ok(())
}
fn decimal(value: &str) -> Result<u32, Error> {
    if value.is_empty() || !value.bytes().all(|b| b.is_ascii_digit()) {
        return Err(Error::InvalidLength);
    }
    value.parse().map_err(|_| Error::InvalidLength)
}
