"""Session packet ABI tests. AES and packet logic run only in the original."""
from emu381 import u32, u64


def session_vectors(emu, generated, record, checked_output):
    # Network::Initialize 0x140021087 writes 4000. This global has no file data.
    emu.uc.mem_write(0x1400A634C, u32(4000))
    # CryptoKey::Initialize 0x140066DFE..E46: original non-AES-NI branch.
    for dst, target in [(0x1400A6358, 0x14006D540),
                        (0x1400A6360, 0x14006D590), (0x1400A6368, 0x14006D6A0)]:
        emu.uc.mem_write(dst, u64(target))
    key0 = generated('session_encrypt', 'aligned_false', 'key0', 16)
    key1 = generated('session_encrypt', 'rotate_send_old', 'key1', 16)
    cases = []

    def state(obj):
        return dict(send=emu.word(obj + 12), receive=emu.word(obj + 16),
                    pending=emu.read(obj + 8, 1)[0])

    def create(with_key=True):
        start = len(emu.calls)
        obj = emu.alloc(784)
        assert emu.call(0x14005EE80, 3, 0, obj, 784) == obj
        if with_key:
            assert emu.call(0x14005F1E0, obj, emu.alloc(16, key0), 16) == 0
        return obj, emu.calls[start:]

    def encrypt(obj, name, message, flag=False, capacity=None, error=0, setup=None):
        capacity = capacity if capacity is not None else ((len(message) + 15) // 16 * 16 + 2)
        buf = emu.alloc(max(capacity, len(message) + 2), b'\xA5\xA5' + message)
        size = emu.alloc(4, u32(capacity))
        before = state(obj)
        start = len(emu.calls)
        result = emu.call(0x14005F3B0, obj, buf, size, len(message), int(flag)) & 0xFFFFFFFF
        assert result == error, (name, result, error)
        output = checked_output(emu, buf, capacity, emu.word(size), message) if not result else b''
        c = record(emu, start, 'session_encrypt', name, '0x14005f3b0',
                   input=message.hex(), output=output.hex(), result=result,
                   key0=key0.hex(), key1=key1.hex(), flag=flag, capacity=capacity,
                   output_length=emu.word(size), before=before, after=state(obj),
                   setup_calls=setup or [], error_output=u32(result).hex())
        cases.append(c)
        return output

    def decrypt(obj, name, packet, error=0, setup=None):
        buf = emu.alloc(len(packet) + 32, packet)
        length, flag = emu.alloc(4, u32(0xA5A5A5A5)), emu.alloc(1, b'\xA5')
        before = state(obj)
        start = len(emu.calls)
        result = emu.call(0x14005F4D0, obj, buf, len(packet), length, flag) & 0xFFFFFFFF
        assert result == error, (name, result, error)
        output = checked_output(emu, buf + 2, len(packet) - 2, emu.word(length) - 2, packet[2:]) if not result else b''
        cases.append(record(emu, start, 'session_decrypt', name, '0x14005f4d0',
                            input=packet.hex(), output=output.hex(), result=result,
                            key0=key0.hex(), key1=key1.hex(), flag=emu.read(flag, 1)[0],
                            output_length=emu.word(length), before=before, after=state(obj),
                            setup_calls=setup or [], error_output=u32(result).hex()))
        return output

    sender, sender_setup = create()
    receiver, receiver_setup = create()
    for name, message, flag in [('aligned_false', bytes(range(16)), False),
                                ('aligned_true', bytes(range(32)), True),
                                ('short_7', b'381 AES', False),
                                ('short_17', bytes(range(17)), True),
                                ('limit_4000', bytes(range(250)) * 16, False)]:
        packet = encrypt(sender, name, message, flag, setup=sender_setup)
        plain = decrypt(receiver, name, packet, setup=receiver_setup)
        assert plain == message + bytes((-len(message)) % 16)
        assert cases[-1]['flag'] == int(flag)

    # Real GenerateKey calls CRT rand 16 times. Supply generated bytes only.
    stream = bytearray()
    def rand_byte():
        if not stream:
            raise RuntimeError('Generated session rand stream exhausted')
        emu.ret(stream.pop(0))
    rand_address = next(a for a, (_, name) in emu.imports.items() if name == 'rand')
    emu.hooks[rand_address] = ('controlled CRT rand for generated session key', rand_byte)
    rotation_setup = {}
    for obj in [sender, receiver]:
        start = len(emu.calls)
        stream.extend(key1)
        key_dst, size = emu.alloc(16, b'\xA5' * 16), emu.alloc(4, u32(16))
        assert emu.call(0x14005F240, obj, key_dst, size, 0) == 0
        assert emu.read(key_dst, 16) == key1 and not stream
        assert state(obj) == dict(send=0, receive=0, pending=1)
        rotation_setup[obj] = emu.calls[start:]
    for tx, rx, name, flag in [(sender, receiver, 'rotate_send_old', False),
                               (receiver, sender, 'rotate_reply_old', True),
                               (sender, receiver, 'rotate_send_new', True),
                               (receiver, sender, 'rotate_reply_new', False)]:
        message = b'381 rotation ' + name.encode()
        packet = encrypt(tx, name, message, flag, setup=rotation_setup[tx])
        plain = decrypt(rx, name, packet, setup=rotation_setup[rx])
        assert plain == message + bytes((-len(message)) % 16)
    assert state(sender) == state(receiver) == dict(send=1, receive=1, pending=0)

    blank, setup = create(False)
    encrypt(blank, 'no_key', b'381 no key', error=3, setup=setup)
    decrypt(blank, 'no_key', bytes.fromhex('0480') + bytes(16), error=3, setup=setup)
    obj, setup = create()
    start = len(emu.calls)
    stream.extend(key1)
    key_dst, key_size = emu.alloc(16, b'\xA5' * 16), emu.alloc(4, u32(16))
    assert emu.call(0x14005F240, obj, key_dst, key_size, 0) == 0
    assert emu.read(key_dst, 16) == key1 and not stream
    setup += emu.calls[start:]
    good = bytes.fromhex(next(c['output'] for c in cases if c['kind'] == 'session_encrypt' and c['case'] == 'aligned_false'))
    wrong = ((int.from_bytes(good[:2], 'little') & 0xFFF) | 0xC000).to_bytes(2, 'little') + good[2:]
    decrypt(obj, 'wrong_tag', wrong, error=7, setup=setup)
    decrypt(obj, 'wrong_active_slot', bytes([good[0], (good[1] & 15) | 0x90]) + good[2:], error=7, setup=setup)
    encrypt(obj, 'too_large', b'\x38' * 4001, error=8, setup=setup)
    encrypt(obj, 'small_buffer', bytes(range(17)), capacity=18, error=9, setup=setup)
    decrypt(obj, 'truncated', good[:-1], error=10, setup=setup)
    for c in cases:
        if c['result']:
            # Error return is the output; an unchanged in-place buffer is not
            # counted as successful cryptographic output.
            assert c['error_output'] != c['input']
    return cases
